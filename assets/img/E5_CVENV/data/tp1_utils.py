def show(images, titles=None, cmap="gray", height=4, ncols=None, **kwargs):
    """Show images side by side (in rows of `ncols`). kwargs go to plt.imshow (vmin, vmax, ...)."""
    ncols = ncols or len(images)
    nrows = -(-len(images) // ncols)
    fig, axes = plt.subplots(nrows, ncols, figsize=(height * 1.6 * ncols, height * nrows), squeeze=False)
    for ax in axes.ravel():
        ax.axis("off")
    for i, (ax, image) in enumerate(zip(axes.ravel(), images)):
        im = ax.imshow(image, cmap=cmap, **kwargs)
        ax.set_title(titles[i] if titles else "")
        if np.ndim(image) == 2:
            fig.colorbar(im, ax=ax, shrink=0.8)
    plt.tight_layout()
    plt.show()


def compare_filters(x, y, filters):
    """filters: dict name -> denoised image. Shows each result, its residual y - x_hat, and its PSNR."""
    from skimage.metrics import peak_signal_noise_ratio
    fig, axes = plt.subplots(2, len(filters), figsize=(3.6 * len(filters), 7))
    for i, (name, x_hat) in enumerate(filters.items()):
        psnr = peak_signal_noise_ratio(x, np.clip(x_hat, 0, 1), data_range=1)
        axes[0, i].imshow(x_hat, cmap="gray", vmin=0, vmax=1)
        axes[0, i].set_title(f"{name}\nPSNR {psnr:.1f} dB")
        axes[1, i].imshow(y - x_hat, cmap="RdBu", vmin=-0.4, vmax=0.4)
        axes[1, i].set_title("residual y - x_hat")
    for ax in axes.ravel():
        ax.axis("off")
    plt.tight_layout()
    plt.show()


