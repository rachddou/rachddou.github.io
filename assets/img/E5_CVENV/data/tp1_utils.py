GRD_SCALE = 270      # gamma0 -> Sentinel-1 GRD digital numbers: DN = 237 sqrt(beta0) and beta0 = gamma0 / tan(38 deg)
SAR2SAR_LOG_RANGE = (-1.429329123112601, 10.089038980848645)    # min and max of log(amplitude) used in training


def despeckle_sar2sar(intensity, apply_network, patch=256):
    """Despeckle a Sentinel-1 intensity image (linear gamma0) with SAR2SAR and YOUR apply_network.

    SAR2SAR was trained on Sentinel-1 GRD amplitudes (digital numbers): the intensity is converted to that
    amplitude, then to a normalized logarithm (speckle becomes additive), processed in overlapping 256 x 256
    patches (averaged where they overlap), and converted back to intensity.
    """
    if torch is None:
        raise ImportError("PyTorch is missing: it is preinstalled on Kaggle and Colab")
    net = _load_weights(Sar2Sar(), "sar2sar.pth")
    lo, hi = SAR2SAR_LOG_RANGE
    z = ((np.log(np.sqrt(np.clip(intensity, 0, None)) * GRD_SCALE + 1e-6) - lo) / (hi - lo)).astype(np.float32)
    height, width = z.shape
    total, count = np.zeros((height, width)), np.zeros((height, width))
    rows = sorted(set(list(range(0, height - patch, patch - 2)) + [height - patch]))
    cols = sorted(set(list(range(0, width - patch, patch - 2)) + [width - patch]))
    for r in rows:
        for c in cols:
            out = np.asarray(apply_network(net, z[r:r + patch, c:c + patch]), dtype=np.float64)
            total[r:r + patch, c:c + patch] += np.exp(np.clip(out, 0, None) * (hi - lo) + lo)    # amplitude
            count[r:r + patch, c:c + patch] += 1
    return ((total / count) / GRD_SCALE) ** 2                                                  # intensity


