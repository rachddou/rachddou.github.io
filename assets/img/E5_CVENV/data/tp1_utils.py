def draw_matches(image1, points1, image2, points2, inliers=None, max_lines=150, title=""):
    """Draw two images side by side with one line per match. points: (N, 2) arrays of (x, y) pixel positions.

    inliers: optional boolean array of length N: inliers are drawn in green, the other matches in red.
    """
    points1, points2 = np.asarray(points1).reshape(-1, 2), np.asarray(points2).reshape(-1, 2)
    inliers = np.ones(len(points1), bool) if inliers is None else np.asarray(inliers).ravel().astype(bool)
    offset = image1.shape[1]
    canvas = np.zeros((max(image1.shape[0], image2.shape[0]), offset + image2.shape[1], 3), np.uint8)
    canvas[:image1.shape[0], :offset] = image1 if image1.ndim == 3 else image1[..., None]
    canvas[:image2.shape[0], offset:] = image2 if image2.ndim == 3 else image2[..., None]
    plt.figure(figsize=(16, 6))
    plt.imshow(canvas)
    keep = np.random.default_rng(0).permutation(len(points1))[:max_lines]
    for i in keep:
        (x1, y1), (x2, y2) = points1[i], points2[i]
        plt.plot([x1, x2 + offset], [y1, y2], "-", color="lime" if inliers[i] else "red", linewidth=0.7)
    plt.title(title or f"{len(points1)} matches ({min(len(points1), max_lines)} drawn)")
    plt.axis("off")
    plt.show()
