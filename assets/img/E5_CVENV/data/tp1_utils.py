class DnCNN(Module):
    """DnCNN (Zhang et al., IEEE TIP 2017): a plain stack of 3 x 3 convolutions that predicts the noise.

    Layout of the weights published by the authors (KAIR): conv + ReLU, (depth - 2) x (conv + ReLU), conv.
    """
    def __init__(self, depth=17, channels=64):
        super().__init__()
        layers = [torch.nn.Conv2d(1, channels, 3, padding=1), torch.nn.ReLU(inplace=True)]
        for _ in range(depth - 2):
            layers += [torch.nn.Conv2d(channels, channels, 3, padding=1), torch.nn.ReLU(inplace=True)]
        layers += [torch.nn.Conv2d(channels, 1, 3, padding=1)]
        self.model = torch.nn.Sequential(*layers)

    def forward(self, y):
        return y - self.model(y)                  # estimated clean image = noisy image - estimated noise


class Sar2Sar(Module):
    """SAR2SAR (Dalsasso, Denis & Tupin, IEEE JSTARS 2021): a U-Net that works on the log of the amplitude.

    Layer names of the weights distributed with the deepdespeckling package (hi-paris, MIT licence).
    """
    def __init__(self):
        super().__init__()
        conv = lambda n_in, n_out: torch.nn.Conv2d(n_in, n_out, 3, padding=1)
        self.enc0, self.enc1 = conv(1, 48), conv(48, 48)
        self.enc2, self.enc3, self.enc4, self.enc5, self.enc6 = (conv(48, 48) for _ in range(5))
        self.dec5, self.dec5b = conv(96, 96), conv(96, 96)
        self.dec4, self.dec4b = conv(144, 96), conv(96, 96)
        self.dec3, self.dec3b = conv(144, 96), conv(96, 96)
        self.dec2, self.dec2b = conv(144, 96), conv(96, 96)
        self.dec1a, self.dec1b, self.dec1 = conv(97, 64), conv(64, 32), conv(32, 1)
        self.pool, self.act = torch.nn.MaxPool2d(2), torch.nn.LeakyReLU(0.1)
        self.up = torch.nn.Upsample(scale_factor=2, mode="nearest")

    def forward(self, y):
        act = self.act
        skips = [y]                                                     # encoder: 5 x (conv, halve the size)
        n = self.pool(act(self.enc1(act(self.enc0(y)))))
        skips.append(n)
        for conv in (self.enc2, self.enc3, self.enc4):
            n = self.pool(act(conv(n)))
            skips.append(n)
        n = act(self.enc6(self.pool(act(self.enc5(n)))))
        for conv, conv_b in ((self.dec5, self.dec5b), (self.dec4, self.dec4b), (self.dec3, self.dec3b),
                             (self.dec2, self.dec2b)):                  # decoder: double the size, reuse the skip
            n = act(conv_b(act(conv(torch.cat([self.up(n), skips.pop()], dim=1)))))
        n = torch.cat([self.up(n), skips.pop()], dim=1)
        return y - self.dec1(act(self.dec1b(act(self.dec1a(n)))))


def _load_weights(net, name, url=None):
    """Load published weights into `net` (tensors only: torch.load never runs code from the file)."""
    net.load_state_dict(torch.load(get_file(name, url), map_location="cpu", weights_only=True))
    return net.eval()                                  # inference mode: no training-specific behaviour


