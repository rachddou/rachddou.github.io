def get_file(name, url=None):
    """Return a local path to `name`: already here, or downloaded from `url`, then from the course website."""
    if os.path.exists(name):
        return name
    for source in [url, DATA_URL + name if DATA_URL else None]:
        if source is None:
            continue
        try:
            with urllib.request.urlopen(source, timeout=60) as response, open(name + ".part", "wb") as f:
                shutil.copyfileobj(response, f)
            if name.endswith(".npz") and not zipfile.is_zipfile(name + ".part"):
                raise ValueError("not an .npz file (error page?)")
            os.replace(name + ".part", name)
            return name
        except Exception as error:
            print(f"could not download {source}: {error}")
    raise FileNotFoundError(f"{name}: could not be downloaded, check the internet access "
                            "(Kaggle: Settings -> Internet -> On)")


def load_npz(name):
    """Load one of the course .npz files: a dict of arrays plus metadata."""
    with np.load(get_file(name)) as f:
        return {key: f[key] for key in f.files}


def crop_to_grid(data, like=None):
    """Cut a course copy to a 10 m pixel grid.

    The course copies are stored a little larger than the study window. `like` is a dict holding the
    `transform` (6 numbers: pixel size and top-left corner in UTM metres) and the `red` band of the target
    window: the copy is cut to exactly the same pixels. With like=None, the reference window is returned.
    """
    transform = np.asarray(data["transform"], dtype=float)
    pixel = transform[0]
    if like is None:
        row, col, height, width = (int(v) for v in data["core"])
    else:
        target = np.asarray(like["transform"], dtype=float)
        height, width = like["red"].shape
        col_exact = (target[2] - transform[2]) / pixel
        row_exact = (target[5] - transform[5]) / -pixel
        col, row = int(round(col_exact)), int(round(row_exact))
        full_height, full_width = next(v.shape for v in data.values() if getattr(v, "ndim", 0) == 2)
        aligned = abs(col_exact - col) < 1e-3 and abs(row_exact - row) < 1e-3 and abs(target[0] - pixel) < 1e-6
        inside = row >= 0 and col >= 0 and row + height <= full_height and col + width <= full_width
        if not (aligned and inside):
            dx, dy = target[2] - transform[2], transform[5] - target[5]      # metres east / south of the copy's corner
            raise ValueError(
                "your window does not fit inside the course copy (top-left corner "
                f"{abs(dx):.0f} m {'east' if dx >= 0 else 'west'} and {abs(dy):.0f} m {'south' if dy >= 0 else 'north'} "
                f"of its corner, size {width} x {height} pixels of {target[0]:g} m). "
                "Check ESIEE and bbox_around in Part 2.1, then rerun from there.")
    out = {}
    for key, value in data.items():
        if getattr(value, "ndim", 0) == 2:
            out[key] = value[row:row + height, col:col + width]
        elif key not in ("transform", "core"):
            out[key] = value
    out["transform"] = np.array([pixel, 0.0, transform[2] + col * pixel, 0.0, -pixel, transform[5] - row * pixel])
    return out


